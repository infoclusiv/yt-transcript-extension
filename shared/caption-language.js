/* Seleccion de subtitulos por idioma original, independiente de display language.
   Utiliza los metadatos del reproductor de YouTube; las heuristicas son fallbacks. */
(function(root) {
  'use strict';
  function normalize(code) {return String(code || '').trim().toLowerCase().replace(/_/g, '-');}
  function basic(code) {return normalize(code).split('-')[0];}
  function isAsr(track) {return track?.autoGenerated === true || track?.kind === 'asr' || String(track?.vssId || '').startsWith('a.');}
  function isSame(a, b) {
    if (!a || !b) return false;
    const A = normalize(a), B = normalize(b);
    if (basic(A) !== basic(B)) return false;
    // Mantener diferenciacion entre subtitulos chinos simplificados y tradicionales.
    if (basic(A) === 'zh') {
      const group = s => /(?:hant|-(?:tw|hk|mo))(?:-|$)/.test(s) ? 'traditional' : 'simplified';
      return group(A) === group(B);
    }
    return true;
  }
  function streamAudioLang(id) {
    const match = String(id || '').match(/^([a-z]{2,3}(?:-[a-z0-9]+)*)\.\d+$/i);
    return match ? normalize(match[1]) : '';
  }
  function extractXtags(tags) {
    if (!tags || typeof atob !== 'function') return '';
    try {
      const normal = String(tags).replace(/-/g, '+').replace(/_/g, '/');
      return atob(normal.padEnd(Math.ceil(normal.length / 4) * 4, '='));
    } catch (_) {return '';}
  }
  function getAudioInfo(playerResponse) {
    const response = playerResponse || {};
    const captions = response.captions?.playerCaptionsTracklistRenderer || {};
    const audioTracks = Array.isArray(captions.audioTracks) ? captions.audioTracks : [];
    const formats = response.streamingData?.adaptiveFormats || [];
    const defaultAudio = audioTracks[captions.defaultAudioTrackIndex ?? 0];
    const explicitlyOriginal = audioTracks.find(a => /\boriginal\b/i.test(
      String(a?.displayName?.simpleText || a?.displayName || a?.audioTrackId || '')));
    const defaultIndex = Number.isInteger(defaultAudio?.defaultCaptionTrackIndex) ? defaultAudio.defaultCaptionTrackIndex :
      (Number.isInteger(captions.defaultCaptionTrackIndex) ? captions.defaultCaptionTrackIndex : undefined);
    for (const format of formats) {
      const id = format?.audioTrack?.id || format?.audioTrack?.audioTrackId;
      const original = extractXtags(format?.xtags);
      const language = streamAudioLang(id);
      if (language && original.includes('acont') && original.includes('original')) {
        return {language, source:'original-audio-tag', defaultCaptionIndex:defaultIndex};
      }
    }
    const stated = normalize(response.videoDetails?.defaultAudioLanguage ||
      response.microformat?.playerMicroformatRenderer?.defaultAudioLanguage ||
      response.videoDetails?.defaultLanguage || '');
    if (stated) return {language:stated, source:'player-metadata', defaultCaptionIndex:defaultIndex};
    const explicit = streamAudioLang(explicitlyOriginal?.audioTrackId);
    if (explicit) return {language:explicit, source:'original-audio-track', defaultCaptionIndex:defaultIndex};
    // defaultAudioTrackIndex puede señalar un doblaje localizado; solo inferir si
    // no hay señal mas fuerte. Se usa despues de examinar pistas ASR.
    return {language:'', source:'unknown', defaultCaptionIndex:defaultIndex,
      defaultAudioLanguage:streamAudioLang(defaultAudio?.audioTrackId)};
  }
  function selectTrack(tracks, settings, playerResponse) {
    const all = (Array.isArray(tracks) ? tracks : []).filter(t => t && t.baseUrl);
    if (!all.length) return null;
    const manual = all.filter(t => !isAsr(t));
    const asr = all.filter(isAsr);
    const choose = (list, lang) => list.find(t => normalize(t.languageCode) === normalize(lang)) ||
      list.find(t => isSame(t.languageCode, lang));
    // Respeta la preferencia EXPLICITA del usuario; no cambia la opcion manual.
    if (settings?.mode === 'language' && settings.languageCode) {
      const selected = choose(manual, settings.languageCode) || choose(asr, settings.languageCode);
      if (selected) return selected;
    }
    const audio = getAudioInfo(playerResponse);
    let language = audio.language;
    if (!language) {
      if (asr.length === 1) {
        language = normalize(asr[0].languageCode);
      } else if (asr.length > 1) {
        // Con doblajes automaticos pueden existir varias pistas ASR; no se
        // puede asumir que la primera ASR sea el idioma original.
        const matchingAsr = asr.filter(t => manual.some(m => isSame(m.languageCode,t.languageCode)));
        if (matchingAsr.length === 1) language = normalize(matchingAsr[0].languageCode);
      }
    }
    if (!language) language = audio.defaultAudioLanguage;
    if (language) {
      const matched = choose(manual,language) || choose(asr,language);
      if (matched) return matched;
    }
    // Si no se identifica el original, no usar navigator.languages ni favorecer ingles.
    // Indice predeterminado de subtitulo/manual/ASR como degradacion segura.
    const def = audio.defaultCaptionIndex != null ? all.find(t => t.index === audio.defaultCaptionIndex) : null;
    if (def && !isAsr(def)) return def;
    return manual[0] || def || asr[0] || all[0];
  }
  root.TranscriptCaptionLanguage = {getAudioInfo,selectTrack,isSame,normalize};
  if (typeof module !== 'undefined' && module.exports) module.exports = root.TranscriptCaptionLanguage;
})(typeof globalThis !== 'undefined' ? globalThis : this);
