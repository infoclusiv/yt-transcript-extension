'use strict';
const assert = require('node:assert/strict');
const language = require('../shared/caption-language.js');
const track = (code, kind='manual', index=0) => ({
  baseUrl: `https://www.youtube.com/api/timedtext?lang=${code}`, languageCode:code,
  autoGenerated:kind==='asr',kind:kind==='asr'?'asr':'',index
});
const encode = s => Buffer.from(s).toString('base64url');
const player = lang => ({streamingData:{adaptiveFormats:[
  {audioTrack:{id:'en.7'},xtags:encode('acont dubbed')},
  {audioTrack:{id:`${lang}.4`},xtags:encode('acont original')}
]}});
function check(label, list, settings, metadata, expected) {
  const got=language.selectTrack(list,settings,metadata);
  assert.equal(got?.languageCode, expected, `${label}: selected ${got?.languageCode}`);
  console.log('PASS:',label, '=>',expected);
}
const auto={mode:'auto',languageCode:''};
const ES=track('es','asr',1), EN=track('en','manual',0), ESman=track('es','manual',2);
check('Spanish original, English manual available, English interface', [EN,ES],auto,player('es'),'es');
check('English original, Spanish manual available', [ESman,EN],auto,player('en'),'en');
check('Prefer manual subtitles in original language over ASR', [EN,ES,ESman],auto,player('es'),'es');
assert.equal(language.selectTrack([EN,ES,ESman],auto,player('es')),ESman);
check('Manual English override remains explicit', [ES,EN],{mode:'language',languageCode:'en'},player('es'),'en');
check('Single ASR fallback independent of navigator language',[EN,ES],auto,{},'es');
check('Auto-dubbed Spanish original with other ASR tracks first',[track('ar','asr'),track('fr','asr'),ES,EN],auto,player('es'),'es');
check('Only English captions available on a Spanish original',[EN],auto,player('es'),'en');
check('No stated original and manual tracks no locale influence',[track('fr'),EN],auto,{},'fr');
check('regional language match es-419',[EN,track('es-419','asr')],auto,player('es'),'es-419');
check('metadata defaultAudioLanguage selects Spanish',[EN,ES],auto,{videoDetails:{defaultAudioLanguage:'es-ES'}},'es');
check('audio original label preferred to default English dub',[EN,ES],auto,{captions:{playerCaptionsTracklistRenderer:{audioTracks:[{audioTrackId:'en.4',displayName:'English'},{audioTrackId:'es.6',displayName:{simpleText:'Spanish (Original)'}}],defaultAudioTrackIndex:0}}},'es');
check('original non-English single ASR without metadata',[track('en','manual'),track('de','asr')],auto,{},'de');
check('no captions',[],auto,{},undefined);
assert.equal(language.isSame('es-419','es'),true);
assert.equal(language.isSame('zh-Hant','zh-Hans'),false);
assert.equal(language.getAudioInfo(player('es')).source,'original-audio-tag');
console.log('All original language tests passed');
